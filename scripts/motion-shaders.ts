// Compiles packages/motion/macos/SparkMotionShaders.metal ahead of time into SparkMotionShaders.metallib.h, the Metal
// library motion loads at run time (docs/motion.md#shader-effects-and-particles). Needs Xcode's Metal toolchain
// (`xcodebuild -downloadComponent MetalToolchain`); apps and CI only read the generated header.
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";

/** Metal 2.0, the lowest language version the shaders need: every GPU macOS 14 runs on (Metal 2 and up) loads them. */
export const METAL_STANDARD = "macos-metal2.0";
export const SHADER_DIRECTORY = path.resolve(import.meta.dirname, "../packages/motion/macos");
export const SHADER_SOURCE = path.join(SHADER_DIRECTORY, "SparkMotionShaders.metal");
export const SHADER_HEADER = path.join(SHADER_DIRECTORY, "SparkMotionShaders.metallib.h");
const sha256 = (bytes: Buffer) => createHash("sha256").update(bytes).digest("hex");

/** The first line of `xcrun metal --version`, or undefined without the Metal toolchain. */
export function metalCompiler(): string | undefined {
  try { return execFileSync("xcrun", ["-sdk", "macosx", "metal", "--version"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).split("\n")[0]!.trim() || undefined; }
  catch { return undefined; }
}

/** Compiles the shader source into library bytes. */
export function compileShaderLibrary(): Buffer {
  const directory = mkdtempSync(path.join(os.tmpdir(), "spark-motion-shaders-"));
  try {
    const air = path.join(directory, "shaders.air"), library = path.join(directory, "shaders.metallib");
    // macOS 14 is motion's deployment target; -frecord-sources=no keeps paths of this machine out of the library.
    execFileSync("xcrun", ["-sdk", "macosx", "metal", "-c", `-std=${METAL_STANDARD}`, "-mmacosx-version-min=14.0", "-O3", "-frecord-sources=no", SHADER_SOURCE, "-o", air], { stdio: "inherit" });
    execFileSync("xcrun", ["-sdk", "macosx", "metallib", air, "-o", library], { stdio: "inherit" });
    return readFileSync(library);
  } finally { rmSync(directory, { recursive: true, force: true }); }
}

/** What the generated header records, and the library bytes it embeds. */
export function readShaderHeader(text = readFileSync(SHADER_HEADER, "utf8")) {
  const define = (name: string) => text.match(new RegExp(`#define ${name} "([^"]*)"`))?.[1];
  const bytes = Buffer.from([...text.split("{")[1]!.matchAll(/0x([0-9a-f]{2})/g)].map(match => parseInt(match[1]!, 16)));
  return { sourceSha256: define("SPARK_MOTION_SHADERS_SOURCE_SHA256"), librarySha256: define("SPARK_MOTION_SHADERS_LIBRARY_SHA256"), compiler: define("SPARK_MOTION_SHADERS_COMPILER"), bytes, sha256: sha256(bytes) };
}

if (import.meta.main) {
  const compiler = metalCompiler();
  if (!compiler) throw new Error("No Metal toolchain: install it with `xcodebuild -downloadComponent MetalToolchain`");
  const bytes = compileShaderLibrary();
  const rows: string[] = [];
  for (let offset = 0; offset < bytes.length; offset += 24) rows.push("  " + [...bytes.subarray(offset, offset + 24)].map(byte => `0x${byte.toString(16).padStart(2, "0")}`).join(", ") + ",");
  writeFileSync(SHADER_HEADER, `// Generated by \`bun run motion:shaders\` from SparkMotionShaders.metal; do not edit.
// The precompiled built-in Metal library of motion's shader effects (docs/motion.md#shader-effects-and-particles).
#pragma once
/** SHA-256 of the SparkMotionShaders.metal this library was compiled from. */
#define SPARK_MOTION_SHADERS_SOURCE_SHA256 "${sha256(readFileSync(SHADER_SOURCE))}"
/** SHA-256 of the library bytes below. */
#define SPARK_MOTION_SHADERS_LIBRARY_SHA256 "${sha256(bytes)}"
/** The compiler that built them (\`xcrun metal --version\`), with -std=${METAL_STANDARD}. */
#define SPARK_MOTION_SHADERS_COMPILER "${compiler}"
static const unsigned char kSparkMotionShaderLibrary[] = {
${rows.join("\n")}
};
`);
  console.log(`SparkMotionShaders.metallib.h: ${bytes.length} bytes, ${METAL_STANDARD}, ${compiler}`);
}
